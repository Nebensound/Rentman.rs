use crate::openapi::{Context, escape, properties, rust_field, rust_member};
use serde_json::Value;
use std::collections::BTreeSet;
use std::fmt::Write as _;

pub fn generate_fields(context: &Context<'_>) -> Result<String, String> {
    let filterable_types = &context.config.filterable_types;
    let schemas = context.schemas;
    let resources = context.resources.values().collect::<BTreeSet<_>>();
    let mut output = String::from(
        "//! Queryable fields of every resource, for typed filters and sorting.\n//!\n//! Each module holds one constant per field Rentman can filter and sort on,\n//! e.g. `contact::COUNTRY`. Fields marked `GENERATED FIELD` have none.\n//!\n//! This file is generated by `cargo xtask update-openapi`.\n\n#![allow(unused_imports)]\n\nuse crate::filter::{EnumFilterValue, Field};\nuse crate::id::{Id, ItemId};\nuse crate::model::*;\nuse chrono::{DateTime, FixedOffset, NaiveDate};\nuse crate::Decimal;\nuse std::marker::PhantomData;\nuse url::Url;\n\n",
    );
    for (name, schema) in schemas {
        if !name.ends_with("Response") {
            continue;
        }
        for (field, field_schema) in properties(schema) {
            if field_schema.get("enum").is_some() {
                writeln!(
                    output,
                    "impl EnumFilterValue for {} {{}}",
                    context.enum_type_name(name, field)
                )
                .unwrap();
            }
        }
    }
    output.push('\n');
    let mut inventory = Vec::new();
    let mut sorted = schemas.iter().collect::<Vec<_>>();
    sorted.sort_by_key(|(name, _)| context.type_name(name));
    for (name, schema) in sorted {
        if !name.ends_with("Response") {
            continue;
        }
        let resource = context.type_name(name).to_owned();
        if !resources.contains(&resource) {
            continue;
        }
        let module = rust_field(&resource);
        writeln!(
            output,
            "/// Queryable fields of [`{resource}`].\npub mod {module} {{\n    use super::*;\n"
        )
        .unwrap();
        let mut seen = BTreeSet::new();
        for (field, field_schema) in properties(schema) {
            if field_schema
                .get("description")
                .and_then(Value::as_str)
                .unwrap_or("")
                .contains("GENERATED FIELD")
            {
                continue;
            }
            let ty = context.base_type(name, field);
            if ty == "CustomFields" {
                continue;
            }
            if !(filterable_types.iter().any(|known| known == ty)
                || ty.starts_with("Id<")
                || field_schema.get("enum").is_some())
            {
                return Err(format!("no filter value type for {name}.{field}: {ty}"));
            }
            let constant = rust_field(field).trim_end_matches('_').to_ascii_uppercase();
            if !seen.insert(constant.clone()) {
                return Err(format!("field constants collide in {module}: {constant}"));
            }
            inventory.push((resource.clone(), field.clone()));
            writeln!(output, "    /// `{}`: {}\n    pub const {constant}: Field<{resource}, {ty}> = Field {{\n        name: \"{}\",\n        types: PhantomData,\n    }};",
                escape(field), context.field_documentation(name, field, ty, None).replace('\n', "\n    /// "), escape(field)).unwrap();
        }
        output.push_str("}\n\n");
    }
    output.push_str("/// Every queryable field: (resource type, Rentman field name).\n#[doc(hidden)]\npub const QUERYABLE_FIELDS: &[(&str, &str)] = &[\n");
    for (resource, field) in inventory {
        writeln!(output, "    (\"{resource}\", \"{}\"),", escape(&field)).unwrap();
    }
    output.push_str("];\n");
    Ok(output)
}

pub fn generate_projection_fields(context: &Context<'_>) -> String {
    let revision_field = context.config.revision_field.as_str();
    let schemas = context.schemas;
    let resources = context.resources.values().collect::<BTreeSet<_>>();
    let mut output = String::from(
        "//! One marker per field of every resource, used by `projection!`.\n//!\n//! Modules carry the resource type name (`Crew`) and markers the field name\n//! of the full model (`firstname`, `r#type`, `vat_code`, `revision`), so a\n//! projection names fields exactly as the model does. Each marker documents\n//! the Rust value a projection field gets.\n//!\n//! This file is generated by `cargo xtask update-openapi`.\n\n#![allow(non_snake_case, non_camel_case_types, unused_imports)]\n\n",
    );
    let imports = [
        "    use crate::ProjectionField;",
        "    use crate::id::{Id, ItemId};",
        "    use crate::model::*;",
        "    use crate::projection::Link;",
        "    use ::chrono::{DateTime, FixedOffset, NaiveDate};",
        "    use crate::{Decimal, Revision};",
        "    use ::url::Url;",
    ];
    let mut sorted = schemas.iter().collect::<Vec<_>>();
    sorted.sort_by_key(|(name, _)| context.type_name(name));
    for (name, schema) in sorted {
        if !name.ends_with("Response") {
            continue;
        }
        let resource = context.type_name(name).to_owned();
        if !resources.contains(&resource) {
            continue;
        }
        let required = projection_required(context, schema);
        writeln!(output, "/// Fields of [`{resource}`](crate::model::{resource}) for `projection!`.\npub mod {resource} {{").unwrap();
        for import in imports {
            writeln!(output, "{import}").unwrap();
        }
        output.push('\n');
        for (field, _) in properties(schema) {
            let value = context.field_type(name, field, &required);
            let wire = if context.field_kind(name, field) == Some("string") && value.contains("Id<")
            {
                value.replace("Id<", "Link<")
            } else {
                value.clone()
            };
            let marker = rust_member(field);
            writeln!(output, "    /// `{}`: {}\n    pub struct {marker};\n\n    impl ProjectionField for {marker} {{\n        type Resource = {resource};\n        type Value = {value};\n        type Wire = {wire};\n        const NAME: &'static str = \"{}\";\n        const REQUIRED: bool = {};\n    }}\n",
                escape(field), context.field_documentation(name, field, &value, Some(required.contains(field))).replace('\n', "\n    /// "), escape(field), required.contains(field)).unwrap();
        }
        writeln!(output, "    /// `revision`: observed version of the item, as on the full model.\n    ///\n    /// Rust value: [`Revision<{resource}>`](crate::Revision). Rentman sends it\n    /// automatically as `{revision_field}`; it is not included in `fields=`.\n    pub struct revision;\n\n    impl ProjectionField for revision {{\n        type Resource = {resource};\n        type Value = Revision<{resource}>;\n        type Wire = Revision<{resource}>;\n        const NAME: &'static str = \"{revision_field}\";\n        const REQUIRED: bool = true;\n    }}\n").unwrap();
        output.push_str("}\n\n");
    }
    output
}

/// Required fields of a resource's projection markers: the documented ones
/// plus the core fields Rentman always sends, but never `custom`.
fn projection_required(context: &Context<'_>, schema: &Value) -> BTreeSet<String> {
    let mut required = crate::openapi::required(schema);
    for field in &context.config.response_core_fields {
        if properties(schema).contains_key(field) {
            required.insert(field.clone());
        }
    }
    required.remove("custom");
    required
}

#[cfg(test)]
// Coverage is disabled for test code so the production 100% gate measures only
// generator behavior.
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use super::*;
    use crate::test_support::{config, spec};
    use serde_json::json;

    #[test]
    fn renders_filter_fields_and_projection_markers() {
        let spec = spec();
        let context = Context::with_config(&spec, config()).unwrap();
        let fields = generate_fields(&context).unwrap();
        for expected in [
            "impl EnumFilterValue for WidgetStatus {}",
            "pub mod widget {",
            "    pub const PART: Field<Widget, Id<Part>> = Field {",
            "    pub const TYPE: Field<Widget, String> = Field {",
            "    (\"Widget\", \"status\"),",
        ] {
            assert!(fields.contains(expected), "missing {expected:?}");
        }
        assert!(!fields.contains("NOTE"));
        assert!(!fields.contains("CUSTOM"));
        assert!(!fields.contains("WidgetPayload"));

        let projections = generate_projection_fields(&context);
        for expected in [
            "pub mod Widget {",
            "    pub struct r#type;",
            "        type Value = Option<Id<Part>>;\n        type Wire = Option<Link<Part>>;",
            "        const NAME: &'static str = \"name\";\n        const REQUIRED: bool = true;",
            "        const NAME: &'static str = \"custom\";\n        const REQUIRED: bool = false;",
            "    pub struct revision;",
        ] {
            assert!(projections.contains(expected), "missing {expected:?}");
        }
    }

    #[test]
    fn projection_markers_require_only_core_fields_a_resource_has() {
        let mut spec = spec();
        spec["components"]["schemas"]["PartResponse"]["properties"]
            .as_object_mut()
            .unwrap()
            .remove("name");
        let context = Context::with_config(&spec, config()).unwrap();
        let projections = generate_projection_fields(&context);
        let part = &projections[projections.find("pub mod Part {").unwrap()
            ..projections.find("pub mod Widget {").unwrap()];
        assert!(part.contains(
            "        const NAME: &'static str = \"id\";\n        const REQUIRED: bool = true;"
        ));
        assert!(!part.contains("pub struct name;"));
    }

    #[test]
    fn rejects_fields_whose_constants_collide() {
        let mut spec = spec();
        let properties = &mut spec["components"]["schemas"]["PartResponse"]["properties"];
        properties["a-b"] = json!({"type": "string"});
        properties["a_b"] = json!({"type": "string"});
        let context = Context::with_config(&spec, config()).unwrap();
        assert_eq!(
            generate_fields(&context),
            Err("field constants collide in part: A_B".to_owned())
        );
    }
}
